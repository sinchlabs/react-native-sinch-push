// swift-tools-version:5.9
//
// Package.swift — SwiftPM harness for the SinchPushSocket core (RN-032).
//
// The core lives in `ios/SinchPushSocket/` and is compiled here exactly as
// CocoaPods compiles it, but with no React Native, no podspec and no Xcode
// project: that is the whole point of the split (see tickets/RN-032.md). It is
// what lets `npm run test:ios` exercise FrameCodec in a plain `swift test`.
//
// Layout:
//   Sources/SinchPushSocket          -> symlink to ../../SinchPushSocket
//   Tests/SinchPushSocketTests/*.swift
//
// The symlink is what keeps one copy of the core sources. SwiftPM refuses a
// target whose resolved path escapes the package root ("target 'X' in package
// 'Y' is outside the package root"), and the core must stay physically in
// `ios/SinchPushSocket/` because that is the directory the podspec globs. So the
// package points at a symlink rather than at the real directory, and nothing is
// duplicated. On a checkout that cannot carry symlinks, run
// `ln -sfn ../../SinchPushSocket Sources/SinchPushSocket` in this directory.
//
// This directory is excluded from the npm tarball (package.json#files) and from
// the podspec's source_files, so neither a symlink nor a test file ships.

import PackageDescription

// Pinned swift-protobuf, and it must be the same number in three places:
//   * buf.gen.swift.yaml      — remote plugin buf.build/apple/swift:v<VERSION>
//   * react-native-sinch-push.podspec — s.dependency "SwiftProtobuf", ">= <V>", "< 2.0"
//   * this file
//
// Why 1.34.1: it is the newest swift-protobuf that still documents a Swift 5.10
// / Xcode 15.3 floor (1.35.0 moves to Xcode 16.0, 1.38.0 to Xcode 16.3). The
// podspec declares ios 13.0 and the repo develops against React Native 0.74, so
// raising the toolchain floor of every host app is a decision to be made
// deliberately, not a side effect of a dependency bump. It is also available
// both as the pinned BSR remote plugin revision and as a CocoaPod, so codegen
// here and `pod install` in a host app agree.
//
// The pod is the wider window on purpose (`>= 1.34.1, < 2.0`): the runtime stays
// source-compatible with code generated by an older 1.x plugin, so only the lower
// bound has to match this file. Pinning `~> 1.34.1` here instead would force a
// `pod install` conflict on any host app already on a later 1.x.
//
// Toolchain: the Package.swift inside swift-protobuf 1.34.1 declares
// swift-tools-version 6.2, so this harness needs Xcode 16.3+ even though the
// shipped pod (swift_versions 5.0, ios 11.0) builds on much older toolchains.
// If `swift test` fails to resolve XCTest, xcode-select is pointing at
// Command Line Tools; `npm run test:ios` sets DEVELOPER_DIR for that case.
//
// `exact:` rather than a range: generated Swift is compiled inside host apps,
// so the runtime that compiles it has to be the one the code was generated
// against. Bump all three together.
let swiftProtobufVersion = Version("1.34.1")

let package = Package(
  name: "SinchPushSocketTests",
  platforms: [
    // The package only ever runs on the host macOS under `swift test`; it is
    // never built for a device. The podspec owns the iOS deployment target.
    .macOS(.v12),
  ],
  dependencies: [
    .package(
      url: "https://github.com/apple/swift-protobuf.git",
      exact: swiftProtobufVersion
    ),
  ],
  targets: [
    // The core, by symlink. `Generated/` is inside it and required: FrameCodec
    // resolves its envelope tags from the generated oneof, so the package does
    // not build until `npm run proto:gen:swift` has run.
    .target(
      name: "SinchPushSocket",
      dependencies: [
        .product(name: "SwiftProtobuf", package: "swift-protobuf"),
      ],
      path: "Sources/SinchPushSocket"
    ),
    // The report path shared with the Notification Service Extension pod
    // (ios/NotificationExtension/Core, by symlink like the core above). It has no
    // dependencies: the extension pod is React- and SwiftProtobuf-free.
    .target(
      name: "SinchPushReportCore",
      path: "Sources/SinchPushReportCore"
    ),
    .testTarget(
      name: "SinchPushReportCoreTests",
      dependencies: ["SinchPushReportCore"],
      path: "Tests/SinchPushReportCoreTests"
    ),
    .testTarget(
      name: "SinchPushSocketTests",
      dependencies: ["SinchPushSocket"],
      path: "Tests/SinchPushSocketTests"
    ),
  ]
)